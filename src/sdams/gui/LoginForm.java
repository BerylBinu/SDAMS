    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword());

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your username and password.");
            return;
        }

        User user = userService.login(username, password);
        if (user == null) {
            JOptionPane.showMessageDialog(this, "Wrong username or password.",
                    "Login failed", JOptionPane.ERROR_MESSAGE);
            txtPassword.setText("");
            return;
        }

        openMenu(user);
    }//GEN-LAST:event_btnLoginActionPerformed
    private void openMenu(User user) {
        switch (user.getRole()) {
            case MANAGER:
                new ManagerMenu((Manager) user).setVisible(true);
                break;
            // Each teammate adds their case when their menu is ready, e.g.:
            // case STUDENT:
            //     new StudentMenu((Student) user).setVisible(true);
            //     break;
            default:
                JOptionPane.showMessageDialog(this,
                        "The " + user.getRole() + " menu is not ready yet.");
                return;   // stay on the login screen
        }
        this.dispose();   // close the login window
    }

